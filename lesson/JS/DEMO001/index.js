// ==========================================
// DEMO001: 変数・定数とコンソール出力
// ==========================================

// 1. 文字列をそのまま出力する
console.log('こんにちは、JavaScript！');

// 2. const（書き換えられない定数）
const siteName = 'zip358.net';
console.log('学習サイト:', siteName);

// 3. let（あとから値を変更できる変数）
let userName = 'ゲスト';
console.log(`ようこそ、${userName}さん！`);

// 変数の値を書き換える
userName = '田中';
console.log(`ようこそ、${userName}さん！`);

